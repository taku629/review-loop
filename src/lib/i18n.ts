export function translate(lang: Lang, s: string, vars?: Vars): string {
  const tpl = lang === 'ja' ? (JA[s] ?? s) : s;
  return vars ? tpl.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : tpl;
}

export const plural = (n: number, word: string) => (n === 1 ? word : `${word}s`);

export function useLang(): Lang {
  return useStore().state.settings.lang ?? 'en';
}

export function useT() {
  const lang = useLang();
  return useCallback((s: string, vars?: Vars) => translate(lang, s, vars), [lang]);
}
